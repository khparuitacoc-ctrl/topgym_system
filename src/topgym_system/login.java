    private void loginButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButton1ActionPerformed
         String uN = username.getText().trim();
        String pW = new String(password.getPassword());
 
        if (uN.isEmpty() || pW.isEmpty()) {
            StatusDialog.warning(this, "Please enter username and password");
            return;
        }
 
        String sql = "SELECT user_id, role FROM ad_tbl WHERE BINARY uname = ? AND BINARY password = ?";
 
        try (Connection conn = DBConnection.connect();
             PreparedStatement pst = conn.prepareStatement(sql)) {
 
            pst.setString(1, uN);
            pst.setString(2, pW);
 
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    int userId = rs.getInt("user_id");
                    String role = rs.getString("role");
 
                    UserSession.setUser(userId, uN, role);
                    StatusDialog.success(this, "Login successful! Welcome, " + role + ".");
 
                    homepage home = new homepage();
                    home.setVisible(true);
                    this.dispose();
                } else {
                    StatusDialog.error(this, "Invalid username or password");
                }
            }
 
        } catch (Exception e) {
            StatusDialog.error(this, "Error: " + e.getMessage());
        }
                                     
     
     
    }//GEN-LAST:event_loginButton1ActionPerformed

